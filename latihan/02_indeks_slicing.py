# Latihan 2 - Indeks dan Slicing
# Input  : string "Pemrograman"
# Proses : akses karakter dengan indeks dan ambil sebagian teks dengan slicing
# Output : karakter pertama, terakhir, empat huruf awal, sisanya, dan teks terbalik

teks = "Pemrograman"
print(teks[0])      # P
print(teks[-1])     # n
print(teks[:4])     # Pemr
print(teks[4:])     # ograman
print(teks[::-1])   # namargormeP
